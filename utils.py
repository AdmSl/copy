"""matematyka kodu"""


def add(a: int, b: int) -> int:
    """matematyka kodu"""
    return a + b


def subtract(a: int, b: int) -> int:
    """matematyka kodu"""
    return a - b


def multiply(a: int, b: int) -> int:
    """matematyka kodu"""
    return a * b


def divide(a: int, b: int) -> float:
    """matematyka kodu"""
    return a / b
